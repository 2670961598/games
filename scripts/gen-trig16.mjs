import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'games/multiplayer/pool-physics/trig16.cjs')

/* TRIG16[i] = round(sin(π/2 · i/2048) · 65536)（Q16.16，四分之一正弦波；
 * 2049 项含端点 i=2048 → 65536——cos 折叠在 idx=0 处取 TRIG16[2048]，缺端点会 NaN） */
const TRIG16 = new Array(2049)
for (let i = 0; i <= 2048; i++) TRIG16[i] = Math.round(Math.sin((Math.PI / 2) * (i / 2048)) * 65536)

/* ATAN8[t] = 四分之一角 brads（2048/圈）：t/2048 ≈ tan(θ)（反正切表，0..2048 → 0..2048） */
const ATAN8 = new Array(2049)
for (let t = 0; t <= 2048; t++) {
  const theta = Math.atan2(t, 2048)          // θ ∈ [0, π/2)
  ATAN8[t] = Math.round((theta / (Math.PI / 2)) * 2048)
}

/* 端点由上方循环直接生成（t=2048 → atan2(2048,2048)=45° → round(0.5·2048)=1024 brads）。
 * F2（GAMES-80）：旧版 length=2048+push(2048) 的手工端点把 [2048] 推成 2048——四分之一
 * 圈 2048 brads 的 45° 应为 1024，删除裁剪回填，全表 2049 项单源生成。 */

